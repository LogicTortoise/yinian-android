    suspend fun deleteById(id: String)

    /**
     * V2: list every task that was generated by the given recurring rule.
     * Used to drop instances when a rule is archived or its horizon moves back.
     */
    @Query("SELECT * FROM tasks WHERE recurringRuleId = :ruleId")
    suspend fun listByRecurringRule(ruleId: String): List<TaskEntity>

    @Query("SELECT * FROM tasks WHERE id = :id")
    suspend fun getById(id: String): TaskEntity?

    /** V2: snapshot of every task in the table. Used by the planner. */
    @Query("SELECT * FROM tasks")
    suspend fun getAllSnapshot(): List<TaskEntity>

    /** V2: snapshot of every open task (status != 'archived'). Used by the planner. */
    @Query("SELECT * FROM tasks WHERE status != 'archived'")
    suspend fun getAllOpenSnapshot(): List<TaskEntity>
}

