package com.yinian.android.data.entity

import androidx.room.Entity
import androidx.room.PrimaryKey

@Entity(tableName = "ideas")
data class IdeaEntity(
    @PrimaryKey val id: String,
    val title: String,
    val body: String,
    val source: String,            // "text" | "voice" | "system"
    val createdAt: Long,
    val updatedAt: Long,
    val archived: Boolean = false,
    val recordingPath: String? = null,
    val transcriptStatus: String = "none" // "none" | "pending" | "ready" | "failed" | "disabled"
)

@Entity(tableName = "tasks")
data class TaskEntity(
    @PrimaryKey val id: String,
    val title: String,
    val notes: String,
    val status: String,            // "open" | "done" | "archived"
    val priority: Int,             // user priority 1..5 (1 highest)
    val estimateMinutes: Int,
    val dueAt: Long? = null,
    val createdAt: Long,
    val updatedAt: Long,
    val derivedFromIdeaId: String? = null,
    val domain: String = "general", // "work" | "life" | "general"
    /** V2: when this task was generated by a recurring rule, link back to the rule. */
    val recurringRuleId: String? = null,
    /**
     * V2: the day key (yyyy-MM-dd in local TZ) that this instance represents when
     * generated by a recurring rule. Null for manually created one-off tasks.
     */
    val instanceDate: String? = null
)

@Entity(tableName = "relations", primaryKeys = ["fromId", "toId", "kind"])
data class RelationEntity(
    val fromId: String,
    val toId: String,
    val kind: String,              // "depends_on" | "related" | "derived_from"
    val createdAt: Long
)

@Entity(tableName = "time_blocks")
data class TimeBlockEntity(
    @PrimaryKey val id: String,
    val taskId: String?,
    val title: String,
    val startAt: Long,
    val endAt: Long,
    val fixed: Boolean = false,
    /**
     * Origin of the block. V1 values "manual" / "system" are preserved.
     * V2 adds "plan" (auto-suggested, applied by the user) and "recurring"
     * (generated by a recurring rule on its scheduled instance).
     */
    val source: String = "manual",
    /** V2: link back to the recurring rule when source == "recurring". */
    val recurringRuleId: String? = null,
    /** V2: the day key (yyyy-MM-dd) for which this recurring instance was generated. */
    val instanceDate: String? = null,
    /**
     * V2: identifier of the applied schedule draft that produced this block.
     * Used to detect duplicate applications of the same draft (idempotence).
     */
    val draftId: String? = null
)

@Entity(tableName = "focus_sessions")
data class FocusSessionEntity(
    @PrimaryKey val id: String,
    val taskId: String?,
    val startedAt: Long,
    val endedAt: Long?,
    /**
     * Total active ms accumulated before the current run. Doubles as the elapsed
     * shown while the session is paused/completed/cancelled.
     */
    val pausedMs: Long = 0,
    /**
     * Wall-clock when the current active segment started. Null when the session
     * is not actively running (paused, completed, or cancelled).
     */
    val activeStartedAt: Long? = null,
    val status: String,            // "active" | "paused" | "completed" | "cancelled"
    val note: String = ""
)

/**
 * V2-ME: one contiguous run/pause interval inside a focus session.
 *
 * Persisted from V2-ME onwards so daily/cross-midnight focus totals can be
 * computed exactly from the segment history. Legacy V3 sessions (which only
 * have [FocusSessionEntity.startedAt]/[pausedMs]/[activeStartedAt]) are
 * attributed using a documented fallback rule at read time — see
 * [com.yinian.android.data.repo.FocusAttribution].
 *
 * - `kind = "active"`: the user was focusing during `[startedAt, endedAt]`.
 *   These rows are summed to compute "actual focus minutes".
 * - `kind = "paused"`: the session was paused during `[startedAt, endedAt]`.
 *   Paused segments are NOT summed and exist only so review screens can show
 *   the pause history if they want to.
 * - `endedAt = null` means the segment is still open; the live segment ends
 *   at the wall-clock "now" used by the attribution function.
 */
@Entity(
    tableName = "focus_session_segments",
    foreignKeys = [
        androidx.room.ForeignKey(
            entity = FocusSessionEntity::class,
            parentColumns = ["id"],
            childColumns = ["sessionId"],
            onDelete = androidx.room.ForeignKey.CASCADE
        )
    ],
    indices = [
        androidx.room.Index("sessionId"),
        androidx.room.Index("startedAt")
    ]
)
data class FocusSessionSegmentEntity(
    @PrimaryKey val id: String,
    val sessionId: String,
    val kind: String,              // "active" | "paused"
    val startedAt: Long,
    val endedAt: Long? = null
)

/**
 * V2: per-weekday work-hours policy. One row per day-of-week (1..7, ISO).
 *
 * - `enabled`: whether this weekday is a working day.
 * - `startMin` / `endMin`: minutes-of-day for the available window.
 * - `bufferMinutes`: rest buffer inserted between blocks.
 * - `dailyCapMinutes`: hard ceiling on the sum of planned minutes for this weekday;
 *   0 means "no explicit cap".
 *
 * Multiple rows per weekday would be allowed by the schema but the planner
 * collapses them to the union of windows; the UI keeps it to one row per day.
 */
@Entity(tableName = "work_policies", primaryKeys = ["dayOfWeek"])
data class WorkPolicyEntity(
    /** 1..7 ISO day-of-week (Monday=1, Sunday=7). */
    val dayOfWeek: Int,
    val enabled: Boolean,
    val startMin: Int,
    val endMin: Int,
    val bufferMinutes: Int = 0,
    val dailyCapMinutes: Int = 0
)

/**
 * V2: a recurring rule that defines how task instances are generated.
 *
 * The rule is intentionally narrow — daily / weekday / weekly frequencies
 * with optional day-of-week selection — so the instance generator stays
 * deterministic and easy to reason about. `byDayMask` is a bitmask where
 * bit (1<<(dow-1)) (dow in 1..7) enables that weekday for weekly rules.
 *
 * - `kind`: "daily" | "weekday" | "weekly".
 * - `startDayKey`: first day key (yyyy-MM-dd, local TZ) from which instances are
 *   generated; the generator never emits an instance before this day.
 * - `horizonDays`: how many days ahead to materialise instances from now.
 * - `anchorTaskId`: optional pointer to the source task the rule was built from;
 *   instances copy title/estimate from `anchorTaskId` at generation time.
 * - `archived`: archived rules never produce new instances.
 */
@Entity(tableName = "recurring_rules")
data class RecurringRuleEntity(
    @PrimaryKey val id: String,
    val title: String,
    val estimateMinutes: Int,
    val priority: Int,
    val domain: String,
    val kind: String,                 // "daily" | "weekday" | "weekly"
    val byDayMask: Int = 0,           // bitmask for weekly (Mon=bit0..Sun=bit6)
    val startDayKey: String,          // yyyy-MM-dd (local)
    val horizonDays: Int = 14,
    val anchorTaskId: String? = null,
    val archived: Boolean = false,
    val createdAt: Long,
    val updatedAt: Long
)

/**
 * V2: a one-off override for a single recurring instance. When present, the
 * instance generator picks this row's title/estimate instead of falling back
 * to the parent rule. `cancelled=true` means the instance was suppressed
 * without altering the parent rule.
 */
@Entity(tableName = "recurring_instances", primaryKeys = ["ruleId", "dayKey"])
data class RecurringInstanceEntity(
    val ruleId: String,
    val dayKey: String,               // yyyy-MM-dd (local)
    val title: String? = null,
    val estimateMinutes: Int? = null,
    val cancelled: Boolean = false,
    val updatedAt: Long = 0L
)

/**
 * V2: a schedule draft produced by the planner. Persisted only after the user
 * applies it. `fingerprint` is a stable hash of the planning inputs and the
 * draft contents so re-applying the same draft is detected and rejected as a
 * no-op. `createdAt` and `appliedAt` let us tell previews from applications.
 */
@Entity(tableName = "schedule_drafts")
data class ScheduleDraftEntity(
    @PrimaryKey val id: String,
    val fingerprint: String,
    val createdAt: Long,
    val appliedAt: Long? = null,
    /** ISO day key (yyyy-MM-dd) for the lower bound of the planning window. */
    val windowStartDay: String,
    /** ISO day key (yyyy-MM-dd) for the upper bound (inclusive) of the planning window. */
    val windowEndDay: String,
    /** Lightweight JSON-free description of placed blocks; used only for debugging. */
    val note: String = ""
)
